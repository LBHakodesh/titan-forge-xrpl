// Two independent graduation gates (pure).
// LEGAL: operator-entered items with document references; never AI-generated.
// ECONOMIC: modeled/observed metrics with explicit thresholds and provenance.
// RULE: profitability NEVER overrides a failing or open legal gate (decideOutcome / outcomeAllowed).
import { priceImpactBps } from '../../public/domain.js';
import { getEngine } from '../engine/index.mjs';
import { SOURCES, SIM } from './model.mjs';

export const LEGAL_ITEMS = [
  { id: 'token_offering_analysis', label: 'Token and offering analysis' },
  { id: 'permitted_market_participants', label: 'Permitted market and participants' },
  { id: 'issuer_trading_requirements', label: 'Issuer and trading requirements' },
  { id: 'approval_documentation', label: 'Approval documentation' },
];
export const LEGAL_ITEM_STATUSES = ['OPEN', 'PASS', 'RESTRICTED', 'FAIL'];
export const GATE_STATUSES = ['OPEN', 'PASS', 'RESTRICTED', 'FAIL'];
export const ECON_ITEMS = [
  { id: 'operating_sustainability', label: 'Operating sustainability' },
  { id: 'verified_demand', label: 'Verified demand evidence' },
  { id: 'funded_liquidity_price_impact', label: 'Funded liquidity and price impact' },
  { id: 'expected_net_mm_returns', label: 'Expected net market-making returns' },
  { id: 'inventory_concentration_risk', label: 'Inventory and concentration risk' },
  { id: 'capital_requirements', label: 'Capital requirements' },
  { id: 'performance_consistency', label: 'Performance consistency' },
];
export const ECON_RULES = { concentrationMax: 0.5, executableShareMin: 0.6, executableShareOpen: 0.3, minDays: 30, positiveDayShareMin: 0.6, sampleOrderUsd: 10_000, minVerifiedEvidence: 2, minParticipants: 15 };
export const PERMISSIONED_DEX_NOTE = 'XRPL Permissioned DEX (with Permissioned Domains / Credentials) is a technical option for a restricted market. Credentials alone do not establish compliance: eligibility rules, KYC and legal approval stay with the operator and counsel.';

const str = (v, n = 300) => (typeof v === 'string' ? v.trim().slice(0, n) : '');

// Normalize operator-entered legal items. PASS/RESTRICTED/FAIL require a document reference, reviewer and date;
// otherwise the item stays OPEN with a reason.
export function normalizeLegalItems(input = {}) {
  return LEGAL_ITEMS.map(({ id, label }) => {
    const x = input[id] || {};
    let status = LEGAL_ITEM_STATUSES.includes(x.status) ? x.status : 'OPEN';
    const docRef = str(x.docRef), reviewer = str(x.reviewer, 120), date = str(x.date, 40);
    let note = str(x.note, 500) || null;
    if (status !== 'OPEN' && (!docRef || !reviewer || !/^\d{4}-\d{2}-\d{2}/.test(date))) { note = `Entered as ${status} without document reference, reviewer and date: held OPEN.`; status = 'OPEN'; }
    return { id, label, status, docRef: docRef || null, reviewer: reviewer || null, date: date || null, note, source: 'OPERATOR_INPUT', aiGenerated: false };
  });
}

export function legalGate(regulatoryReview = {}, itemsInput = {}) {
  const items = normalizeLegalItems(itemsInput);
  const rs = regulatoryReview.status || 'NOT_STARTED';
  const reasons = [];
  let status;
  if (rs === 'NOT_ELIGIBLE' || items.some((i) => i.status === 'FAIL')) {
    status = 'FAIL'; reasons.push(rs === 'NOT_ELIGIBLE' ? 'Regulatory review: NOT_ELIGIBLE (operator input).' : 'A legal item is marked FAIL.');
  } else if (rs === 'RESTRICTED_PATHWAY' && items.every((i) => i.status === 'PASS' || i.status === 'RESTRICTED')) {
    status = 'RESTRICTED'; reasons.push('Counsel indicates a restricted pathway; all items documented.');
  } else if (rs === 'COUNSEL_OPINION_RECEIVED' && items.every((i) => i.status === 'PASS')) {
    status = 'PASS'; reasons.push('Counsel opinion received and every legal item documented as PASS.');
  } else {
    status = 'OPEN';
    if (rs !== 'COUNSEL_OPINION_RECEIVED' && rs !== 'RESTRICTED_PATHWAY') reasons.push(`Regulatory review is ${rs} (operator input).`);
    const open = items.filter((i) => i.status === 'OPEN').map((i) => i.label);
    if (open.length) reasons.push(`Open items: ${open.join(', ')}.`);
  }
  return { status, items, reasons, regulatoryReview: { ...regulatoryReview, source: 'OPERATOR_INPUT' }, source: 'OPERATOR_INPUT',
    note: 'Legal status is reviewer input entered by an operator, never generated by Titan Ghost Intelligence.' };
}

const item = (id, status, value, threshold, evidence, provenance) => ({ id, label: ECON_ITEMS.find((x) => x.id === id).label, status, value, threshold, evidence, provenance });

// Economic gate. `perf` = simulateInterim() (or null); states = capital states; project carries operator inputs.
export function economicGate({ project, states, perf, engine = getEngine() }) {
  const items = [];
  const months = project.targetOperatingPeriod?.months ?? 0;
  const runway = project.runwayMonths ?? 0;
  items.push(item('operating_sustainability', runway >= months && months > 0 ? 'PASS' : runway > 0 ? 'OPEN' : 'FAIL',
    `${runway} months runway`, `≥ ${months} months (target operating period)`, [project.sustainabilityMeasures || '—'], 'OPERATOR_INPUT'));

  const ev = project.demand?.verifiedEvidence || [];
  const parts = project.demand?.independentParticipants ?? 0;
  const dOk = ev.length >= ECON_RULES.minVerifiedEvidence && parts >= ECON_RULES.minParticipants;
  items.push(item('verified_demand', dOk ? 'PASS' : 'OPEN', `${ev.length} verified evidence refs · ${parts} independent participants`,
    `≥ ${ECON_RULES.minVerifiedEvidence} refs and ≥ ${ECON_RULES.minParticipants} participants`, ev.map((e) => `${e.ref}: ${e.description}`), 'OPERATOR_INPUT'));

  const funded = SOURCES.reduce((s, id) => s + (states[id]?.FUNDED || 0), 0);
  const alloc = funded > 0 ? engine.allocate(funded, { flowScale: 1, ringsActive: 6 }) : null;
  const impact = alloc ? priceImpactBps(ECON_RULES.sampleOrderUsd, alloc.rings) : Infinity;
  const maxImpact = project.mmEconomics?.targetSpreadBps ?? 50;
  items.push(item('funded_liquidity_price_impact', Number.isFinite(impact) && impact <= maxImpact ? 'PASS' : funded > 0 ? 'FAIL' : 'OPEN',
    `$${Math.round(funded).toLocaleString('en-US')} funded · ${Number.isFinite(impact) ? impact + ' bps' : 'exceeds depth'} for a $${ECON_RULES.sampleOrderUsd.toLocaleString('en-US')} order`,
    `≤ ${maxImpact} bps (project target spread)`, [`Engine: ${engine.info().label}`], SIM));

  const net = perf?.totals?.netMmReturnUsd;
  items.push(item('expected_net_mm_returns', perf && perf.totals.positionUsd > 0 ? (net > 0 ? 'PASS' : 'FAIL') : 'OPEN',
    perf ? `$${Math.round(net).toLocaleString('en-US')} net over ${perf.days} days` : 'no executable position', '> $0 after costs (excl. inventory appreciation)',
    perf ? [`Realized $${Math.round(perf.totals.realizedUsd)}`, `Costs $${Math.round(perf.totals.costsUsd)}`, `Inventory appreciation $${Math.round(perf.totals.inventoryAppreciationUsd)} (excluded)`] : [], perf?.mode || SIM));

  const exec = SOURCES.map((id) => ({ id, usd: states[id]?.EXECUTABLE || 0 }));
  const execTotal = exec.reduce((s, x) => s + x.usd, 0);
  const top = exec.sort((a, b) => b.usd - a.usd)[0];
  const topShare = execTotal ? top.usd / execTotal : 1;
  items.push(item('inventory_concentration_risk', execTotal === 0 ? 'OPEN' : topShare <= ECON_RULES.concentrationMax ? 'PASS' : 'FAIL',
    execTotal ? `${top.id} supplies ${(topShare * 100).toFixed(1)}% of executable capital` : 'no executable capital', `no source > ${ECON_RULES.concentrationMax * 100}%`,
    [`Max inventory skew target ${project.mmEconomics?.maxInventorySkewPct ?? '—'}%`], SIM));

  const reqTotal = SOURCES.reduce((s, id) => s + (states[id]?.REQUESTED || 0), 0);
  const share = reqTotal ? execTotal / reqTotal : 0;
  items.push(item('capital_requirements', share >= ECON_RULES.executableShareMin ? 'PASS' : share >= ECON_RULES.executableShareOpen ? 'OPEN' : 'FAIL',
    `${(share * 100).toFixed(1)}% of requested capital executable`, `≥ ${ECON_RULES.executableShareMin * 100}% executable`, ['REQUESTED, MATCHED, COMMITTED, FUNDED and EXECUTABLE are tracked separately per source.'], SIM));

  const days = perf?.days ?? 0, pos = perf?.totals?.positiveDayShare ?? 0;
  items.push(item('performance_consistency', !perf || perf.totals.positionUsd === 0 || days < ECON_RULES.minDays ? 'OPEN' : pos >= ECON_RULES.positiveDayShareMin ? 'PASS' : 'FAIL',
    perf ? `${(pos * 100).toFixed(0)}% positive days over ${days}` : 'no record', `≥ ${ECON_RULES.positiveDayShareMin * 100}% over ≥ ${ECON_RULES.minDays} days`, [], perf?.mode || SIM));

  const status = items.some((i) => i.status === 'FAIL') ? 'FAIL' : items.every((i) => i.status === 'PASS') ? 'PASS' : 'OPEN';
  return { status, items, engine: engine.info(), mode: SIM };
}

// Outcome from the two gates. Legal is evaluated FIRST and economics can never lift a non-PASS legal gate.
export function decideOutcome(legal, economic) {
  const reasons = [];
  const econPass = economic.status === 'PASS';
  const sustainFail = economic.items?.find((i) => i.id === 'operating_sustainability')?.status === 'FAIL';
  let outcome;
  if (legal.status === 'FAIL') { outcome = 'DECLINE'; reasons.push('Legal gate FAIL: declined regardless of modeled profitability.'); }
  else if (legal.status === 'OPEN') { outcome = 'REMAIN_IN_INCUBATION'; reasons.push('Legal gate OPEN: the project-token corridor is not available until legal review is complete.'); }
  else if (legal.status === 'RESTRICTED') { outcome = econPass ? 'RESTRICTED_MARKET_PATHWAY' : 'REMAIN_IN_INCUBATION'; reasons.push(econPass ? `Restricted pathway: ${PERMISSIONED_DEX_NOTE}` : 'Restricted pathway documented, economic gate not yet passed.'); }
  else if (econPass) { outcome = 'GRADUATE_TO_TOKEN_CORRIDOR'; reasons.push('Both gates PASS.'); }
  else if (economic.status === 'FAIL' && sustainFail) { outcome = 'DECLINE'; reasons.push('Operating sustainability fails.'); }
  else { outcome = 'REMAIN_IN_INCUBATION'; reasons.push(`Economic gate ${economic.status}: continue XRP/RLUSD incubation.`); }
  const legalOverride = econPass && legal.status !== 'PASS' && legal.status !== 'RESTRICTED';
  if (legalOverride) reasons.push('Economic gate passes, but profitability does not override the legal gate.');
  return { outcome, reasons, legalOverride };
}

// Which outcomes an operator may record. GRADUATE needs legal PASS + economic PASS; RESTRICTED needs legal
// PASS/RESTRICTED + economic PASS. REMAIN and DECLINE (more conservative) are always permitted.
export function outcomeAllowed(outcome, legal, economic) {
  const reasons = [];
  if (outcome === 'GRADUATE_TO_TOKEN_CORRIDOR') {
    if (legal.status !== 'PASS') reasons.push(`Legal gate is ${legal.status}: graduation refused. Profitability never overrides the legal gate.`);
    if (economic.status !== 'PASS') reasons.push(`Economic gate is ${economic.status}.`);
  } else if (outcome === 'RESTRICTED_MARKET_PATHWAY') {
    if (!['PASS', 'RESTRICTED'].includes(legal.status)) reasons.push(`Legal gate is ${legal.status}: restricted pathway needs documented counsel input.`);
    if (economic.status !== 'PASS') reasons.push(`Economic gate is ${economic.status}.`);
  } else if (!['REMAIN_IN_INCUBATION', 'DECLINE'].includes(outcome)) reasons.push(`Unknown outcome ${outcome}.`);
  return { allowed: reasons.length === 0, reasons };
}
