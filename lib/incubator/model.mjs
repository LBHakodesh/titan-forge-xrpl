const num = (v) => (typeof v === 'string' && v.trim() !== '' ? Number(v) : v);
const isAmt = (v) => typeof v === 'number' && Number.isFinite(v) && v >= 0;
const round2 = (x) => Math.round(x * 100) / 100;
const usdOf = (v) => num(v && typeof v === 'object' ? v.usd : v);

export const tierCombination = (s) => TIER_SOURCES.filter((t) => (s?.[t]?.usd ?? 0) > 0).join('+') || null;

// Validate + normalize a TGLB capital stack. Returns { ok, errors, stack }.
export function validateStack(input = {}) {
  const errors = [];
  const targetUsd = num(input.targetUsd);
  if (!(typeof targetUsd === 'number' && Number.isFinite(targetUsd) && targetUsd > 0 && targetUsd <= 1_000_000_000)) errors.push('targetUsd must be a number > 0 and ≤ 1,000,000,000.');
  const src = input.sources || {};
  const sources = {};
  for (const id of SOURCES) {
    const v = usdOf(src[id] ?? 0);
    if (!isAmt(v)) { errors.push(`${id} must be a number ≥ 0 (zero is allowed for unused sources).`); sources[id] = { usd: 0 }; continue; }
    sources[id] = { usd: round2(v) };
  }
  const tierSum = TIER_SOURCES.reduce((s, t) => s + sources[t].usd, 0);
  if (tierSum <= 0) errors.push('All three tiers are zero: at least one of Tier 1 / Tier 2 / Tier 3 must be nonzero.');
  else if (Number.isFinite(targetUsd) && Math.abs(tierSum - targetUsd) > 0.5) errors.push(`Tier allocations sum to $${round2(tierSum).toLocaleString('en-US')}, target is $${round2(targetUsd).toLocaleString('en-US')}: they must match (project-owned and proprietary lines are separate and not part of the TGLB target).`);
  for (const t of TIER_SOURCES) sources[t].pct = targetUsd > 0 ? round2((sources[t].usd / targetUsd) * 100) : 0;

  const terms = {};
  if (sources.T2.usd > 0) {
    const t = { ...DEFAULT_T2_TERMS, ...(input.terms?.T2 || {}), earlyExit: { ...DEFAULT_T2_TERMS.earlyExit, ...(input.terms?.T2?.earlyExit || {}) }, model: 'CONTRACTUAL' };
    t.termDays = num(t.termDays); t.earlyExit.noticeDays = num(t.earlyExit.noticeDays); t.earlyExit.penaltyBps = num(t.earlyExit.penaltyBps);
    if (!(Number.isInteger(t.termDays) && t.termDays >= 1 && t.termDays <= 1825)) errors.push('T2 termDays must be an integer 1–1825.');
    if (!(Number.isInteger(t.earlyExit.noticeDays) && t.earlyExit.noticeDays >= 0 && t.earlyExit.noticeDays <= 365)) errors.push('T2 early-exit noticeDays must be an integer 0–365.');
    if (!(isAmt(t.earlyExit.penaltyBps) && t.earlyExit.penaltyBps <= 10_000)) errors.push('T2 early-exit penaltyBps must be 0–10,000.');
    t.walletPermissions = 'Not established by this contractual model: protocol-enforced wallet permissions are a separate control.';
    terms.T2 = t;
  }
  if (sources.T3.usd > 0) {
    const t = { ...DEFAULT_T3_TERMS, ...(input.terms?.T3 || {}) };
    if (!T3_UNDERWRITING.includes(t.underwriting)) errors.push(`T3 underwriting must be one of ${T3_UNDERWRITING.join(', ')}.`);
    t.aprBps = num(t.aprBps); t.termMonths = num(t.termMonths);
    if (!(isAmt(t.aprBps) && t.aprBps <= 10_000)) errors.push('T3 aprBps must be 0–10,000.');
    if (!(Number.isInteger(t.termMonths) && t.termMonths >= 1 && t.termMonths <= 120)) errors.push('T3 termMonths must be an integer 1–120.');
    if (t.disbursed && t.underwriting !== 'APPROVED') errors.push('T3 cannot be disbursed before underwriting is APPROVED.');
    t.mode = SIM; t.nativeLending = 'UNAVAILABLE';
    terms.T3 = t;
  }
  const stack = { targetUsd: Number.isFinite(targetUsd) ? round2(targetUsd) : null, combination: tierCombination(sources), sources, terms, mode: SIM };
  return { ok: errors.length === 0, errors, stack };
}

// Ownership view (I2): T1/T2 are participant-owned and never project-owned.
export function ownership(stack) {
  const s = stack.sources;
  return {
    participantOwnedUsd: s.T1.usd + s.T2.usd, creditorFinancedUsd: s.T3.usd, projectOwnedUsd: s.PROJECT.usd, proprietaryUsd: s.PROPRIETARY.usd,
    note: 'Tier 1 and Tier 2 capital belongs to TGLW participants. It is never project money.',
  };
}
export const projectOwnedUsd = (stack) => stack.sources.PROJECT.usd;

// ---------- Capital states (I3) ----------
export function initialStates(stack) {
  return Object.fromEntries(SOURCES.map((id) => [id, { REQUESTED: stack.sources[id].usd, MATCHED: 0, COMMITTED: 0, FUNDED: 0, EXECUTABLE: 0 }]));
}

// Check one source's states; extra rules for T3 (underwriting gates commitment and funding).
export function checkSourceStates(id, st, { t3 } = {}) {
  const errors = [];
  for (const k of CAPITAL_STATES) if (!isAmt(st?.[k])) errors.push(`${id}.${k} must be a number ≥ 0.`);
  if (errors.length) return errors;
  for (let i = 1; i < CAPITAL_STATES.length; i++) {
    const a = CAPITAL_STATES[i - 1], b = CAPITAL_STATES[i];
    if (st[b] > st[a] + 1e-9) errors.push(`${id}: ${b} ($${st[b]}) cannot exceed ${a} ($${st[a]}).`);
  }
  if (id === 'T3' && t3) {
    if (t3.underwriting === 'DECLINED' && (st.MATCHED > 0 || st.COMMITTED > 0 || st.FUNDED > 0 || st.EXECUTABLE > 0)) errors.push('T3 was declined by the lending partner: nothing past REQUESTED may be nonzero.');
    if (t3.underwriting !== 'APPROVED' && st.COMMITTED > 0) errors.push('T3 cannot be COMMITTED before underwriting is APPROVED and a loan agreement exists.');
    if (!t3.disbursed && st.FUNDED > 0) errors.push('T3 cannot be FUNDED before disbursement.');
  }
  return errors;
}

export function checkStates(states, stack) {
  const errors = [];
  for (const id of SOURCES) {
    if (!states[id]) { errors.push(`Missing capital states for ${id}.`); continue; }
    errors.push(...checkSourceStates(id, states[id], { t3: stack?.terms?.T3 }));
    if (stack && Math.abs(states[id].REQUESTED - stack.sources[id].usd) > 0.5) errors.push(`${id}: REQUESTED must equal the stack amount ($${stack.sources[id].usd}).`);
  }
  return errors;
}

// Pure update of ONE source's states (I3). Other sources are copied untouched.
export function setSourceStates(states, stack, id, patch = {}) {
  if (!SOURCES.includes(id)) return { ok: false, errors: [`Unknown source ${id}.`], states };
  const next = { ...states };
  const cur = { ...states[id] };
  for (const k of CAPITAL_STATES) if (k !== 'REQUESTED' && patch[k] != null) cur[k] = num(patch[k]);
  next[id] = cur;
  const errors = checkSourceStates(id, cur, { t3: stack?.terms?.T3 });
  return errors.length ? { ok: false, errors, states } : { ok: true, errors: [], states: next };
}

// Re-base states on a new stack: REQUESTED follows the stack; later states are clipped down, never raised.
export function rebaseStates(states, stack) {
  const out = {};
  for (const id of SOURCES) {
    const prev = states?.[id] || {};
    let cap = stack.sources[id].usd;
    out[id] = { REQUESTED: cap };
    for (const k of CAPITAL_STATES.slice(1)) { const v = Math.min(cap, Math.max(0, prev[k] || 0)); out[id][k] = v; cap = v; }
    if (id === 'T3' && stack.terms?.T3?.underwriting === 'DECLINED') for (const k of CAPITAL_STATES.slice(1)) out[id][k] = 0;
  }
  return out;
}

// Honest "unavailable funding" view: shortfalls between consecutive states, per source.
export function fundingGaps(states, stack) {
  const gaps = [];
  for (const id of SOURCES) {
    const s = states[id];
    if (!s || s.REQUESTED <= 0) continue;
    const t3declined = id === 'T3' && stack?.terms?.T3?.underwriting === 'DECLINED';
    if (t3declined) { gaps.push({ source: id, kind: 'DECLINED', shortfallUsd: s.REQUESTED, text: `Tier 3 financing of $${s.REQUESTED.toLocaleString('en-US')} was declined by the lending partner (SIMULATION). It is unavailable, not pending.` }); continue; }
    if (s.MATCHED < s.REQUESTED) gaps.push({ source: id, kind: 'MATCH_SHORTFALL', shortfallUsd: round2(s.REQUESTED - s.MATCHED), text: `${SOURCE_DEFS[id].label}: matched $${s.MATCHED.toLocaleString('en-US')} of $${s.REQUESTED.toLocaleString('en-US')} requested.` });
    if (s.EXECUTABLE < s.MATCHED) gaps.push({ source: id, kind: 'NOT_YET_EXECUTABLE', shortfallUsd: round2(s.MATCHED - s.EXECUTABLE), text: `${SOURCE_DEFS[id].label}: $${round2(s.MATCHED - s.EXECUTABLE).toLocaleString('en-US')} matched but not executable (commitment, funding or delegation outstanding).` });
  }
  return gaps;
}

// Per-state totals across sources (each state kept separate; never collapsed into one number).
export function stateTotals(states) {
  return Object.fromEntries(CAPITAL_STATES.map((k) => [k, round2(SOURCES.reduce((s, id) => s + (states[id]?.[k] || 0), 0))]));
}

// ---------- Custody boundary (I2, I4) ----------
// Destinations: 'OWNER_LIQUIDITY_POSITION' (owner's own TGLW position), 'PROGRAM_LIQUIDITY' (quoting inventory),
// 'PROJECT_TREASURY', 'GYW1313', 'EXTERNAL'.
export const DESTINATIONS = ['OWNER_LIQUIDITY_POSITION', 'PROGRAM_LIQUIDITY', 'PROJECT_TREASURY', 'GYW1313', 'EXTERNAL'];

export function custodyCheck({ source, to, amountUsd, ownerAuthorization } = {}) {
  const violations = [];
  const def = SOURCE_DEFS[source];
  if (!def) return { allowed: false, executes: false, mode: SIM, violations: [`Unknown source ${source}.`] };
  if (!DESTINATIONS.includes(to)) violations.push(`Unknown destination ${to}.`);
  if (!(typeof amountUsd === 'number' && amountUsd > 0)) violations.push('amountUsd must be > 0.');
  const auth = ownerAuthorization && typeof ownerAuthorization === 'object' && ownerAuthorization.owner === def.owner && ownerAuthorization.by && ownerAuthorization.at;
  if (def.transferRequiresOwnerAuth && !auth) violations.push(`${def.label}: no transfer without the owner's (${def.owner}) explicit authorization.`);
  if ((source === 'T1' || source === 'T2') && !['OWNER_LIQUIDITY_POSITION', 'PROGRAM_LIQUIDITY'].includes(to)) violations.push(`${def.label} is participant-owned and liquidity-only: it can never be moved to ${to}. It is not project money.`);
  if (source === 'T3' && !['PROGRAM_LIQUIDITY'].includes(to)) violations.push('Tier 3 loan proceeds are restricted to the permitted use (program market-making inventory).');
  return { allowed: violations.length === 0, executes: false, mode: SIM, violations,
    note: violations.length ? 'Refused at the custody boundary. Nothing was moved.' : 'Would be permissible as a SIMULATION record only. Nothing is moved by this tab.' };
}
